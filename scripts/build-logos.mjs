#!/usr/bin/env node
// Generates src/lib/logos.ts from the Simple Icons package (CC0 artwork).
//   npm i --prefix /tmp/si simple-icons && node scripts/build-logos.mjs /tmp/si/node_modules/simple-icons
// Logos are trademarks of their owners and are only used to identify hardware on your own network.
// To drop all logos, replace src/lib/logos.ts with `export const LOGOS: Record<string, string> = {};`
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join, resolve } from 'node:path';

const dir = resolve(process.argv[2] ?? 'node_modules/simple-icons');
const si = await import(pathToFileURL(join(dir, 'index.mjs')).href).catch(() => import(pathToFileURL(join(dir, 'index.js')).href));
const bySlug = new Map(Object.values(si).filter((i) => i && i.slug).map((i) => [i.slug, i]));

const WANT = 'apple samsung google xiaomi huawei intel raspberrypi espressif tplink ubiquiti netgear asus dell hp lenovo sony playstation lg sonos philipshue ring nvidia synology qnap epson roku cisco mikrotik oneplus oppo vivo motorola nokia bose steam amd acer homeassistant proxmox vmware openwrt meta tesla honor garmin fitbit shelly ikea wyze arlo razer lifx tado'.split(' ');
const out = {}, missing = [];
for (const s of WANT) { const i = bySlug.get(s); if (i) out[s] = i.path; else missing.push(s); }

const body = Object.entries(out).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
writeFileSync(new URL('../src/lib/logos.ts', import.meta.url), `// GENERATED by scripts/build-logos.mjs from Simple Icons (CC0). 24x24 single-colour paths.
// Brand logos are trademarks of their respective owners; they are used only to identify the hardware on
// your own network. Replace this file with \`export const LOGOS: Record<string, string> = {};\` to remove them.
export const LOGOS: Record<string, string> = {
${body}
};
`);
console.log(`${Object.keys(out).length} logos written${missing.length ? `, missing: ${missing.join(' ')}` : ''}`);
